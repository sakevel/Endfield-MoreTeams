"""Original deterministic vector marks; shared 5/64 stroke and white alpha only.

SVG is the editable source, PNG is embedded in Lua so no game asset or disk loader
is needed. Pillow renders the same line/circle primitives at 4x resolution.
"""
from pathlib import Path
from PIL import Image, ImageDraw
import base64, io, json

ROOT = Path(__file__).resolve().parents[1]
STROKE = 5
# Existing persisted mark IDs 2..16, simplified at 24px display size.
ICONS = [
    ('guard', [[(18,46),(46,18)],[(15,36),(28,49)],[(38,15),(49,26)],[(20,44),(13,51)]]),
    ('defender', [[(15,14),(49,14),(47,38),(32,51),(17,38),(15,14)],[(32,23),(32,40)]]),
    ('support', [[(32,11),(32,53)],[(11,32),(53,32)],[(17,17),(47,47)],[(17,47),(47,17)]]),
    ('caster', [[(32,10),(51,32),(32,54),(13,32),(32,10)],[(23,32),(41,32)]]),
    ('vanguard', [[(14,25),(32,12),(50,25)],[(14,39),(32,26),(50,39)],[(32,28),(32,53)]]),
    ('striker', [[(32,10),(32,54)],[(10,32),(54,32)],[(19,19),(19,45),(45,45),(45,19),(19,19)]]),
    ('protocol', [[(16,51),(16,17),(32,9),(48,17),(48,51)],[(25,48),(25,28),(39,28),(39,48)],[(12,51),(52,51)]]),
    ('energy', [[(35,9),(16,34),(30,34),(26,55),(49,28),(35,28),(35,9)]]),
    ('monument', [[(12,52),(52,52)],[(20,46),(24,13),(40,13),(44,46)],[(24,13),(32,8),(40,13)],[(32,22),(32,37)]]),
    ('danger', [[(32,10),(54,50),(10,50),(32,10)],[(32,24),(32,36)],[(32,42),(32,44)]]),
    ('fragment', [[(32,9),(51,30),(38,32),(42,49),(25,55),(13,34),(27,33),(22,17),(32,9)]]),
    ('relic', [[(32,11),(51,22),(51,43),(32,54),(13,43),(13,22),(32,11)],[(13,22),(32,33),(51,22)],[(32,33),(32,54)]]),
    ('echo', [[(15,53),(15,38),(23,38),(23,25),(31,25),(31,12),(43,12),(43,53)],[(10,53),(54,53)],[(32,12),(32,8)]]),
    ('training', [[(11,11),(21,11)],[(11,11),(11,21)],[(43,11),(53,11),(53,21)],[(11,43),(11,53),(21,53)],[(43,53),(53,53),(53,43)],[(32,22),(32,42)],[(22,32),(42,32)]]),
    ('exploration', [[(32,10),(51,21),(51,43),(32,54),(13,43),(13,21),(32,10)],[(24,40),(30,24),(40,23),(34,39),(24,40)]]),
]

def render():
    out = ROOT/'design/marks'; out.mkdir(parents=True, exist_ok=True)
    atlas = Image.new('RGBA',(256,256))
    for index,(name,paths) in enumerate(ICONS):
        im=Image.new('L',(256,256)); d=ImageDraw.Draw(im)
        for path in paths:
            pts=[(x*4,y*4) for x,y in path]
            d.line(pts,fill=255,width=STROKE*4,joint='curve')
            for x,y in pts:
                r=STROKE*2;d.ellipse((x-r,y-r,x+r,y+r),fill=255)
        alpha=im.resize((64,64),Image.Resampling.LANCZOS)
        # RGB is white everywhere (including transparent texels), never gray baked in.
        tile=Image.new('RGBA',(64,64),(255,255,255,255));tile.putalpha(alpha)
        atlas.paste(tile,((index%4)*64,(index//4)*64))
        svg='<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" fill="none" stroke="white" stroke-width="5" stroke-linecap="round" stroke-linejoin="round">\n'
        for path in paths: svg+='  <polyline points="'+' '.join(f'{x},{y}'for x,y in path)+'"/>\n'
        (out/(name+'.svg')).write_text(svg+'</svg>\n',encoding='utf8')
    data=io.BytesIO();atlas.save(data,format='PNG',optimize=True)
    png=data.getvalue()
    (out/'atlas.png').write_bytes(png)
    # Preview of original vector assets, not extracted/modified game textures.
    sheet=Image.new('RGBA',(640,240),(49,49,49,255))
    for index in range(15):
        tile=atlas.crop(((index%4)*64,(index//4)*64,(index%4+1)*64,(index//4+1)*64))
        for row,size in enumerate((24,48)):
            sheet.alpha_composite(tile.resize((size,size),Image.Resampling.LANCZOS),((index%8)*80+16,(index//8)*120+row*54+12))
    (ROOT/'artifacts').mkdir(exist_ok=True);sheet.convert('RGB').save(ROOT/'artifacts/marks-preview.png')
    b64=base64.b64encode(png).decode()
    lua="""-- Original vector icon atlas, generated by tools/draw-marks.py. Do not hand edit.
do
    local W=_G.ZMLMoreTeams
    function W.createMarks()
        local U=CS.UnityEngine
        local tex=U.Texture2D(2,2,U.TextureFormat.RGBA32,false)
        local icons={}
        local ok,sprites=pcall(function()
            assert(U.ImageConversion.LoadImage(tex,CS.System.Convert.FromBase64String('%s'),true),'Mark atlas decode failed')
            tex.name='ZMLTeamMarks';tex.wrapMode=U.TextureWrapMode.Clamp;tex.filterMode=U.FilterMode.Bilinear
            for i=0,14 do
                icons[i+2]=U.Sprite.Create(tex,U.Rect(i%%4*64,192-math.floor(i/4)*64,64,64),U.Vector2(.5,.5),100,0,U.SpriteMeshType.FullRect)
            end
            return icons
        end)
        if not ok then
            for _,sprite in pairs(icons)do U.Object.Destroy(sprite)end
            U.Object.Destroy(tex);error(sprites)
        end
        return tex,sprites
    end
end
""" % b64
    (ROOT/'mod/marks.lua').write_text(lua,encoding='utf8')
    (out/'index.json').write_text(json.dumps({'stroke':STROKE,'viewBox':64,'ids':{i+2:name for i,(name,_)in enumerate(ICONS)}},indent=2),encoding='utf8')
    print(f'Original marks: {len(ICONS)}, atlas {len(png)} bytes; SVG + Lua regenerated')

if __name__=='__main__':render()
